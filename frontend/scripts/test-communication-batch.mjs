import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/communicationBatch.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { verifyCommunicationBatch, selectVerificationCandidates } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const people = Array.from({ length: 27 }, (_, i) => ({ id: `person-${i}`, name: '同名人选', job_ids: [`job-${i % 3}`], communication_status: 'mutual' }));
const calls = [], saved = [], progress = [];
assert.deepEqual(selectVerificationCandidates(people, ['person-25', 'person-2', 'person-25']).map(p => p.id), ['person-25', 'person-2']);
assert.deepEqual(selectVerificationCandidates(people, []), [], 'empty date range must never expand to all local candidates');
assert.throws(() => selectVerificationCandidates(people, ['missing']));
assert.throws(() => selectVerificationCandidates(people, undefined));
let active = 0;
const result = await verifyCommunicationBatch([...people, people[0]], async ids => {
  assert.equal(active++, 0, 'BOSS verification must be sequential');
  calls.push(ids); await new Promise(resolve => setImmediate(resolve)); active--;
  return { total: ids.length, candidates: ids.map(id => ({ ...people.find(row => row.id === id), communication_status: id === 'person-0' ? 'unknown' : 'mutual' })) };
}, rows => saved.push(...rows), p => progress.push(p));
assert.deepEqual(calls.map(batch => batch.length), [10, 10, 7]);
assert.deepEqual(calls.flat(), people.map(row => row.id), 'all jobs and previously verified people must participate');
assert.equal(saved.length, 27);
assert.deepEqual(result, { total: 27, completed: 27, verified: 27, classified: 26, unknown: 1, failed: 0, failures: [] });
assert.equal(progress.at(-1).completed, 27);
let batches = 0;
const partial = await verifyCommunicationBatch(people, async ids => {
  if (++batches === 2) throw new Error('temporary failure');
  return { total: ids.length, candidates: people.filter(row => ids.includes(row.id)) };
}, () => {}, () => {});
assert.equal(batches, 3, 'later people must still be verified after a failed batch');
assert.equal(partial.verified, 17); assert.equal(partial.failed, 10); assert.equal(partial.completed, 27);
assert.deepEqual(partial.failures[0].ids, people.slice(10, 20).map(row => row.id));
const mismatch = await verifyCommunicationBatch(people.slice(0, 1), async () => ({ total: 1, candidates: [people[1]] }), () => assert.fail('mismatched data must not update UI'), () => {});
assert.equal(mismatch.failed, 1);
const empty = await verifyCommunicationBatch([], () => assert.fail('empty list must not call BOSS'), () => {}, () => {});
assert.equal(empty.total, 0);
const notOpened = await verifyCommunicationBatch(people.slice(0, 1), async () => ({ total: 1, candidates: [{ ...people[0], communication_status: 'unknown', communication_evidence: null, communication_error: '未找到目标会话' }] }), () => {}, () => {});
assert.equal(notOpened.verified, 0, 'failure to open a chat must not be counted as verified');
assert.equal(notOpened.failed, 1);
assert.equal(notOpened.unknown, 0);
console.log('Full verification passed: 27 people across jobs, all batches, known statuses rechecked, sequential calls, partial failures, identity validation and empty list.');
